/// Loader families understood by the public model.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
#[non_exhaustive]
pub enum LoaderKind {
    Fabric,
    Forge,
    NeoForge,
    Quilt,
}

impl LoaderKind {
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::Fabric => "fabric",
            Self::Forge => "forge",
            Self::NeoForge => "neoforge",
            Self::Quilt => "quilt",
        }
    }
}

impl fmt::Display for LoaderKind {
    fn fmt(&self, formatter: &mut fmt::Formatter<'_>) -> fmt::Result {
        formatter.write_str(self.as_str())
    }
}

impl FromStr for LoaderKind {
    type Err = Error;

    fn from_str(value: &str) -> Result<Self> {
        match value.to_ascii_lowercase().as_str() {
            "fabric" => Ok(Self::Fabric),
            "forge" => Ok(Self::Forge),
            "neoforge" => Ok(Self::NeoForge),
            "quilt" => Ok(Self::Quilt),
            _ => Err(LoaderError::UnsupportedKind(value.to_owned()).into()),
        }
    }
}

/// Versioned loader selection attached to an instance.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct LoaderConfig {
    pub kind: LoaderKind,
    pub version: String,
}

impl LoaderConfig {
    pub fn new(kind: LoaderKind, version: impl Into<String>) -> Result<Self> {
        let value = Self {
            kind,
            version: version.into(),
        };
        value.validate()?;
        Ok(value)
    }

    /// Validates a portable, exact loader version coordinate.
    pub fn validate(&self) -> Result<()> {
        if self.version.eq_ignore_ascii_case("latest")
            || self.version.is_empty()
            || self.version.len() > 128
            || !self.version.bytes().all(|byte| {
                byte.is_ascii_alphanumeric() || matches!(byte, b'.' | b'-' | b'_' | b'+')
            })
        {
            return Err(LoaderError::InvalidVersion(self.version.clone()).into());
        }
        Ok(())
    }
}

/// Reproducible identity embedded in every loader plan.
